#!/usr/bin/env node
/**
 * 生成原型用的真实 fixture（只使用公开 API 已有字段）。
 *
 * 与 `../status-detail/fixtures.mjs` 的数值完全一致；唯一区别是
 * `buckets_24h` 的 ts 改成后端真实约定：最后一个桶是当前小时，
 * 往前共 24 个桶（旧 fixture 从当天 00:00 开始，会出现「现在」在 14:34
 * 却排在 18:00 之后的时间轴矛盾）。
 *
 * 用法 / Usage: node web/screenshots/detail-polish/make-fixture.mjs
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { detailFixture } from "./fixtures.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const HOUR = 3_600;
const NOW = Math.floor(Date.now() / 1_000);
const CURRENT = NOW - (NOW % HOUR);

function rolling(source) {
  return Array.from({ length: 24 }, (_, index) => {
    const bucket = source[index] ?? null;
    if (bucket === null) return null;
    return { ...bucket, ts: CURRENT - (23 - index) * HOUR };
  });
}

function shape(state) {
  const data = detailFixture(state);
  const server = data.servers[0];
  return {
    generated_at: NOW,
    server: {
      ...server,
      buckets_24h: rolling(server.buckets_24h ?? []),
    },
  };
}

const payload = {
  healthy: shape("healthy"),
  incident: shape("incident"),
  offline: shape("offline"),
};

const body = `/* 生成文件，请勿手改 / generated by make-fixture.mjs */
window.PW_FIXTURES = ${JSON.stringify(payload, null, 2)};
`;
writeFileSync(path.join(HERE, "fixtures-data.js"), body);
console.log(
  `wrote fixtures-data.js (now=${NOW}, bucket ends=${new Date(CURRENT * 1000).toISOString()})`,
);
